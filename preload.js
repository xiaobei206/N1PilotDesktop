const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('pilot', {
  connect: (config) => ipcRenderer.invoke('ssh:connect', config),
  setAppLanguage: (language) => ipcRenderer.invoke('app:set-language', language),
  getChatProxy: () => ipcRenderer.invoke('chat:get-proxy'),
  applyChatProxy: (config) => ipcRenderer.invoke('chat:apply-proxy', config),
  trustHost: (fingerprint) => ipcRenderer.invoke('ssh:trust-host', fingerprint),
  inspectCommand: (command) => ipcRenderer.invoke('ssh:inspect-command', command),
  exec: (sessionId, command, timeoutSeconds, approvedRisk, runId) => ipcRenderer.invoke('ssh:exec', sessionId, command, timeoutSeconds, approvedRisk === true, runId),
  startTerminal: (sessionId, cols, rows) => ipcRenderer.invoke('ssh:terminal:start', sessionId, cols, rows),
  writeTerminal: (sessionId, data) => ipcRenderer.send('ssh:terminal:write', sessionId, data),
  resizeTerminal: (sessionId, cols, rows) => ipcRenderer.send('ssh:terminal:resize', sessionId, cols, rows),
  disconnect: (sessionId) => ipcRenderer.invoke('ssh:disconnect', sessionId),
  listSshProfiles: () => ipcRenderer.invoke('ssh:profiles:list'),
  saveSshProfile: (config) => ipcRenderer.invoke('ssh:profiles:save', config),
  deleteSshProfile: (key) => ipcRenderer.invoke('ssh:profiles:delete', key),
  setSftpExpanded: (expanded) => ipcRenderer.invoke('window:set-sftp-expanded', expanded),
  minimizeWindow: () => ipcRenderer.invoke('window:minimize'),
  toggleMaximizeWindow: () => ipcRenderer.invoke('window:toggle-maximize'),
  closeWindow: () => ipcRenderer.invoke('window:close'),
  localHome: () => ipcRenderer.invoke('sftp:local-home'),
  pickLocalDirectory: () => ipcRenderer.invoke('sftp:pick-local-directory'),
  listLocal: (localPath) => ipcRenderer.invoke('sftp:list-local', localPath),
  listRemote: (sessionId, remotePath) => ipcRenderer.invoke('sftp:list-remote', sessionId, remotePath),
  openRemoteEditor: (sessionId, remotePath) => ipcRenderer.invoke('editor:open-remote-file', sessionId, remotePath),
  uploadFiles: (sessionId, localPaths, remoteDir, overwrite, transferId) => ipcRenderer.invoke('sftp:upload-files', sessionId, localPaths, remoteDir, overwrite, transferId),
  downloadFiles: (sessionId, remotePaths, localDir, transferId) => ipcRenderer.invoke('sftp:download-files', sessionId, remotePaths, localDir, transferId),
  copyLocalFiles: (paths, targetDir) => ipcRenderer.invoke('sftp:copy-local-files', paths, targetDir),
  localProperties: (localPath) => ipcRenderer.invoke('sftp:local-properties', localPath),
  showLocalProperties: (localPath) => ipcRenderer.invoke('sftp:show-local-properties', localPath),
  remoteProperties: (sessionId, remotePath) => ipcRenderer.invoke('sftp:remote-properties', sessionId, remotePath),
  mkdirLocal: (dir, name) => ipcRenderer.invoke('sftp:mkdir-local', dir, name),
  mkdirRemote: (sessionId, dir, name) => ipcRenderer.invoke('sftp:mkdir-remote', sessionId, dir, name),
  renameLocal: (path, name) => ipcRenderer.invoke('sftp:rename-local', path, name),
  renameRemote: (sessionId, path, name) => ipcRenderer.invoke('sftp:rename-remote', sessionId, path, name),
  moveLocal: (path, dir) => ipcRenderer.invoke('sftp:move-local', path, dir),
  moveRemote: (sessionId, path, dir) => ipcRenderer.invoke('sftp:move-remote', sessionId, path, dir),
  deleteLocal: (paths) => ipcRenderer.invoke('sftp:delete-local', paths),
  deleteRemote: (sessionId, paths) => ipcRenderer.invoke('sftp:delete-remote', sessionId, paths),
  chmodRemote: (sessionId, path, mode) => ipcRenderer.invoke('sftp:chmod-remote', sessionId, path, mode),
  chownRemote: (sessionId, path, uid, gid) => ipcRenderer.invoke('sftp:chown-remote', sessionId, path, uid, gid),
  prepareRemoteDrag: (sessionId, paths) => ipcRenderer.invoke('sftp:prepare-remote-drag', sessionId, paths),
  cleanupNativeDrag: (paths) => ipcRenderer.invoke('sftp:cleanup-native-drag', paths),
  startNativeDrag: (paths) => ipcRenderer.send('app:start-native-drag', paths),
  debugLog: (record) => ipcRenderer.send('debug:log', record),
  getDebugSettings: () => ipcRenderer.invoke('app:get-debug-settings'),
  setDebugEnabled: (enabled) => ipcRenderer.invoke('app:set-debug-enabled', enabled === true),
  openDebugLogFolder: () => ipcRenderer.invoke('app:open-debug-log-folder'),
  getPathForFile: (file) => webUtils.getPathForFile(file),
  copyText: (text) => ipcRenderer.invoke('app:copy-text', text),
  readClipboard: () => ipcRenderer.invoke('app:read-clipboard'),
  quit: () => ipcRenderer.invoke('app:quit'),
  on: (channel, callback) => {
    const allowed = new Set(['ssh:status', 'ssh:host-key-pending', 'ssh:output', 'ssh:terminal:data', 'ssh:terminal:status', 'app:log', 'sftp:progress', 'sftp:drag-status']);
    if (!allowed.has(channel)) return;
    ipcRenderer.on(channel, (_event, data) => callback(data));
  }
});
